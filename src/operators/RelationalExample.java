package operators;

public class RelationalExample{
    public static void main(String[] args){
        int A = 10, B = 5;

        System.out.println("A == B : " + (A == B));
        System.out.println("A != B : " + (A != B));
        System.out.println("A > B : " + (A > B));
        System.out.println("A < B : " + (A < B));
        System.out.println("A >= B : " + (A >= B));
        System.out.println("A <= B : " + (A <= B));
        System.out.println();
    }
}